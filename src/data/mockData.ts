export function generateHistoricalData(basePrice: number, days: number = 90): PricePoint[] {
  const data: PricePoint[] = [];
  let currentPrice = basePrice * 0.85;
  const today = new Date();

  for (let i = days - 1; i >= 0; i--) {
    const date = new Date(today);
    date.setDate(date.getDate() - i);

    const volatility = 0.02;
    const change = (Math.random() - 0.48) * volatility * currentPrice;
    currentPrice = Math.max(currentPrice * 0.7, Math.min(currentPrice * 1.2, currentPrice + change));

    const open = currentPrice * (1 + (Math.random() - 0.5) * 0.01);
    const close = currentPrice * (1 + (Math.random() - 0.5) * 0.01);
    const high = Math.max(open, close) * (1 + Math.random() * 0.01);
    const low = Math.min(open, close) * (1 - Math.random() * 0.01);
    const volume = Math.floor(Math.random() * 5000000) + 1000000;

    data.push({
      date: date.toISOString().split('T')[0],
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  return data;
}

export function generateIndexHistoricalData(baseValue: number, days: number = 90): PricePoint[] {
  const data: PricePoint[] = [];
  let currentValue = baseValue * 0.9;
  const today = new Date();

  for (let i = days - 1; i >= 0; i--) {
    const date = new Date(today);
    date.setDate(date.getDate() - i);

    const volatility = 0.012;
    const change = (Math.random() - 0.48) * volatility * currentValue;
    currentValue = currentValue + change;

    const open = currentValue * (1 + (Math.random() - 0.5) * 0.005);
    const close = currentValue * (1 + (Math.random() - 0.5) * 0.005);
    const high = Math.max(open, close) * (1 + Math.random() * 0.003);
    const low = Math.min(open, close) * (1 - Math.random() * 0.003);
    const volume = Math.floor(Math.random() * 100000000) + 50000000;

    data.push({
      date: date.toISOString().split('T')[0],
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  return data;
}

